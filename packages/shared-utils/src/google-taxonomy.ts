/**
 * Returns the Google Merchant Center category mapping for a given category name, slug, or breadcrumb string.
 */
export function getGoogleProductCategory(categoryInput?: string): GoogleCategoryMapping {
  if (!categoryInput) return DEFAULT_GOOGLE_CATEGORY;

  const normalized = categoryInput
    .toLowerCase()
    .trim()
    .replace(/\s+/g, "-")
    .replace(/[^a-z0-9-]/g, "");

  if (!normalized) return DEFAULT_GOOGLE_CATEGORY;

  // Direct slug match
  if (GOOGLE_PRODUCT_TAXONOMY[normalized]) {
    return GOOGLE_PRODUCT_TAXONOMY[normalized];
  }

  // Substring or token matching
  for (const [key, mapping] of Object.entries(GOOGLE_PRODUCT_TAXONOMY)) {
    if (normalized.includes(key) || key.includes(normalized)) {
      return mapping;
    }
  }

  // Broad keyword matching
  if (normalized.includes("helmet")) return GOOGLE_PRODUCT_TAXONOMY["motorcycle-helmets"];
  if (normalized.includes("jacket")) return GOOGLE_PRODUCT_TAXONOMY["riding-jackets"];
  if (normalized.includes("pant") || normalized.includes("jean")) return GOOGLE_PRODUCT_TAXONOMY["riding-pants"];
  if (normalized.includes("glove")) return GOOGLE_PRODUCT_TAXONOMY["riding-gloves"];
  if (normalized.includes("boot") || normalized.includes("shoe")) return GOOGLE_PRODUCT_TAXONOMY["motorcycle-riding-boots"];
  if (normalized.includes("bag") || normalized.includes("luggage")) return GOOGLE_PRODUCT_TAXONOMY["luggage-touring"];
  if (normalized.includes("intercom") || normalized.includes("bluetooth")) return GOOGLE_PRODUCT_TAXONOMY["intercoms"];
  if (normalized.includes("spare") || normalized.includes("part")) return GOOGLE_PRODUCT_TAXONOMY["bike-spares"];

  return DEFAULT_GOOGLE_CATEGORY;
}
