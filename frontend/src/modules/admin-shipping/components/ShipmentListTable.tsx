"use client";

import React, { useState, useEffect } from "react";
import { format } from "date-fns";
import { toast } from "sonner";
import { 
  Search, 
  RefreshCw, 
  Printer, 
  Copy, 
  Truck, 
  CheckCircle2, 
  AlertTriangle, 
  Clock, 
  ExternalLink,
  ChevronLeft,
  ChevronRight
} from "lucide-react";
import { useAdminShipments, useSyncTracking } from "@/core/hooks/useAdminShipments";
import { IShipment } from "@store4riders/shared-types";
import { AdminTrackingModal } from "./AdminTrackingModal";

export const ShipmentListTable = () => {
  const [page, setPage] = useState(1);
  const [limit, setLimit] = useState(15);
  const [search, setSearch] = useState("");
  const [statusFilter, setStatusFilter] = useState("");
  const [providerFilter, setProviderFilter] = useState("");
  const [debouncedSearch, setDebouncedSearch] = useState("");
  const [selectedTrackingOrder, setSelectedTrackingOrder] = useState<any | null>(null);

  // Debounce search
  useEffect(() => {
    const handler = setTimeout(() => {
      setDebouncedSearch(search.trim());
      setPage(1);
    }, 400);
    return () => clearTimeout(handler);
  }, [search]);

  const { data, isLoading, isFetching, refetch } = useAdminShipments({
    page,
    limit,
    search: debouncedSearch,
    status: statusFilter,
    provider: providerFilter,
  });

  const syncMutation = useSyncTracking();

  const handleSync = (shipmentId: string) => {
    syncMutation.mutate(shipmentId, {
      onSuccess: () => {
        toast.success("Courier tracking synced successfully!");
        refetch();
      },
      onError: (err: any) => {
        toast.error(err?.message || "Failed to sync courier tracking");
      },
    });
  };

  const handleCopyAwb = (awb?: string) => {
    if (!awb) return;
    navigator.clipboard.writeText(awb);
    toast.success(`AWB ${awb} copied!`);
  };

  const handlePrintLabel = (labelUrl?: string) => {
    if (labelUrl) {
      window.open(labelUrl, "_blank");
    } else {
      toast.error("Shipping label not yet generated by courier partner.");
    }
  };

  const getProviderBadge = (provider?: string, courierName?: string) => {
    const p = (provider || "").toLowerCase();
    if (p.includes("delhivery")) {
      return (
        <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-bold uppercase tracking-wider bg-red-50 text-red-700 border border-red-200">
          Delhivery
        </span>
      );
    }
    if (p.includes("xpressbees")) {
      return (
        <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-bold uppercase tracking-wider bg-purple-50 text-purple-700 border border-purple-200">
          Xpressbees
        </span>
      );
    }
    if (p.includes("shiprocket")) {
      return (
        <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-bold uppercase tracking-wider bg-orange-50 text-orange-700 border border-orange-200">
          Shiprocket
        </span>
      );
    }
    return (
      <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-bold uppercase tracking-wider bg-slate-100 text-slate-700 border border-slate-200">
        {courierName || provider || "Direct Courier"}
      </span>
    );
  };

  const getStatusBadge = (status?: string) => {
    const s = (status || "").toUpperCase();
    if (s === "DELIVERED") {
      return (
        <span className="inline-flex items-center gap-1.5 px-2 py-0.5 rounded-full text-[10px] font-bold bg-emerald-50 text-emerald-800 border border-emerald-200 whitespace-nowrap">
          <span className="w-1.5 h-1.5 rounded-full bg-emerald-500"></span>
          Delivered
        </span>
      );
    }
    if (s === "OUT_FOR_DELIVERY") {
      return (
        <span className="inline-flex items-center gap-1.5 px-2 py-0.5 rounded-full text-[10px] font-bold bg-indigo-50 text-indigo-800 border border-indigo-200 whitespace-nowrap">
          <span className="w-1.5 h-1.5 rounded-full bg-indigo-500"></span>
          Out for Delivery
        </span>
      );
    }
    if (["IN_TRANSIT", "SHIPPED", "PICKED_UP"].includes(s)) {
      return (
        <span className="inline-flex items-center gap-1.5 px-2 py-0.5 rounded-full text-[10px] font-bold bg-blue-50 text-blue-800 border border-blue-200 whitespace-nowrap">
          <span className="w-1.5 h-1.5 rounded-full bg-blue-500"></span>
          In Transit
        </span>
      );
    }
    if (["READY_TO_SHIP", "AWB_ASSIGNED", "SHIPMENT_CREATED"].includes(s)) {
      return (
        <span className="inline-flex items-center gap-1.5 px-2 py-0.5 rounded-full text-[10px] font-bold bg-sky-50 text-sky-800 border border-sky-200 whitespace-nowrap">
          <span className="w-1.5 h-1.5 rounded-full bg-sky-500"></span>
          Packed &amp; Ready
        </span>
      );
    }
    if (["RTO_INITIATED", "RTO_DELIVERED", "FAILED", "CANCELLED", "LOST", "DAMAGED", "NDR"].includes(s)) {
      return (
        <span className="inline-flex items-center gap-1.5 px-2 py-0.5 rounded-full text-[10px] font-bold bg-rose-50 text-rose-800 border border-rose-200 whitespace-nowrap">
          <span className="w-1.5 h-1.5 rounded-full bg-rose-500"></span>
          Delivery Issue
        </span>
      );
    }
    return (
      <span className="inline-flex items-center gap-1.5 px-2 py-0.5 rounded-full text-[10px] font-bold bg-slate-100 text-slate-700 border border-slate-200 whitespace-nowrap">
        <span className="w-1.5 h-1.5 rounded-full bg-slate-400"></span>
        {status?.replace(/_/g, " ") || "Processing"}
      </span>
    );
  };

  const shipments = data?.items || [];
  const total = data?.total || 0;
  const totalPages = Math.ceil(total / limit) || 1;

  return (
    <div className="bg-white border border-slate-200 shadow-sm rounded-2xl overflow-hidden flex flex-col justify-between font-sans">
      
      {/* Filters Bar */}
      <div>
        <div className="p-3 border-b border-slate-200 bg-slate-50/70 flex flex-col md:flex-row gap-2.5 justify-between items-center">
          
          {/* Search Bar */}
          <div className="relative w-full md:w-96">
            <Search className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
            <input
              type="text"
              placeholder="Search by AWB number or Order ID..."
              value={search}
              onChange={(e) => setSearch(e.target.value)}
              className="w-full pl-9 pr-8 py-2 bg-white border border-slate-300 rounded-lg text-xs font-medium focus:outline-none focus:border-brand focus:ring-1 focus:ring-brand shadow-sm"
            />
            {search && (
              <button
                onClick={() => setSearch("")}
                className="absolute right-2.5 top-1/2 -translate-y-1/2 text-slate-400 hover:text-slate-700 text-xs font-bold"
              >
                ✕
              </button>
            )}
          </div>
          
          {/* Dropdown Filters */}
          <div className="flex items-center gap-2 w-full md:w-auto">
            <select 
              value={providerFilter} 
              onChange={(e) => { setProviderFilter(e.target.value); setPage(1); }}
              className="border border-slate-300 bg-white rounded-lg px-3 py-2 text-xs font-bold text-slate-700 focus:outline-none focus:border-brand shadow-sm"
            >
              <option value="">All Couriers</option>
              <option value="shiprocket">Shiprocket</option>
              <option value="delhivery">Delhivery</option>
              <option value="xpressbees">Xpressbees</option>
              <option value="manual">Manual Dispatch</option>
            </select>
            
            <select 
              value={statusFilter} 
              onChange={(e) => { setStatusFilter(e.target.value); setPage(1); }}
              className="border border-slate-300 bg-white rounded-lg px-3 py-2 text-xs font-bold text-slate-700 focus:outline-none focus:border-brand shadow-sm"
            >
              <option value="">All Statuses</option>
              <option value="AWB_ASSIGNED">Packed &amp; Ready</option>
              <option value="IN_TRANSIT">In Transit</option>
              <option value="OUT_FOR_DELIVERY">Out for Delivery</option>
              <option value="DELIVERED">Delivered</option>
              <option value="RTO_INITIATED">RTO / Issue</option>
            </select>

            <button
              onClick={() => refetch()}
              disabled={isFetching}
              className="inline-flex items-center gap-1.5 px-3 py-2 rounded-lg bg-slate-900 hover:bg-slate-800 text-white text-xs font-bold transition-colors shadow-sm disabled:opacity-50"
              title="Refresh carrier shipments"
            >
              <RefreshCw className={`w-3.5 h-3.5 ${isFetching ? "animate-spin text-amber-400" : ""}`} />
              <span className="hidden sm:inline">Refresh</span>
            </button>
          </div>

        </div>

        {/* Table Content */}
        <div className={`overflow-x-auto transition-opacity duration-200 ${isFetching ? "opacity-60" : "opacity-100"}`}>
          <table className="w-full text-left border-collapse table-auto">
            <thead>
              <tr className="bg-slate-100/70 border-b border-slate-200 text-[11px] font-bold text-slate-500 uppercase tracking-wider">
                <th className="py-2.5 px-3 w-[18%]">Order #</th>
                <th className="py-2.5 px-3 w-[18%]">Carrier &amp; Partner</th>
                <th className="py-2.5 px-3 w-[22%]">AWB Number</th>
                <th className="py-2.5 px-3 w-[18%]">Transit Status</th>
                <th className="py-2.5 px-3 w-[14%]">Dispatch Date</th>
                <th className="py-2.5 px-3 w-[10%] text-right">Actions</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100 text-xs text-slate-700">
              {isLoading ? (
                <tr>
                  <td colSpan={6} className="py-20 text-center text-slate-400 font-semibold">
                    <div className="w-7 h-7 border-3 border-brand border-t-transparent rounded-full animate-spin mx-auto mb-2"></div>
                    Loading carrier shipments...
                  </td>
                </tr>
              ) : shipments.length === 0 ? (
                <tr>
                  <td colSpan={6} className="py-20 text-center text-slate-400">
                    <Truck className="w-10 h-10 text-slate-300 mx-auto mb-2" />
                    <p className="font-bold text-slate-700">No shipments found</p>
                    <p className="text-xs text-slate-500 mt-0.5">
                      {debouncedSearch ? `No shipments matching "${debouncedSearch}"` : "Dispatched orders will appear here once an AWB is generated."}
                    </p>
                  </td>
                </tr>
              ) : (
                shipments.map((shipment: IShipment) => {
                  const shipmentId = shipment.id || String(shipment._id);
                  const orderNum = shipment.orderNumber || shipment.orderId?.slice(-8)?.toUpperCase() || "ORD";

                  return (
                    <tr key={shipmentId} className="hover:bg-slate-50/80 transition-colors">
                      
                      {/* Order # */}
                      <td className="py-2.5 px-3 align-top">
                        <div className="flex flex-col">
                          <span className="font-bold text-slate-900 font-mono text-xs">
                            #{orderNum}
                          </span>
                          <span className="text-[10px] text-slate-500 uppercase font-medium mt-0.5">
                            {shipment.shipmentType === "reverse" ? "Reverse Return" : "Forward Order"}
                          </span>
                        </div>
                      </td>

                      {/* Carrier & Partner Span */}
                      <td className="py-2.5 px-3 align-top">
                        <div className="flex flex-col gap-1 items-start">
                          {getProviderBadge(shipment.provider, shipment.courierName)}
                          {shipment.courierName && shipment.provider !== shipment.courierName && (
                            <span className="text-[11px] text-slate-500 font-medium pl-0.5">
                              {shipment.courierName}
                            </span>
                          )}
                        </div>
                      </td>

                      {/* AWB Number Span */}
                      <td className="py-2.5 px-3 align-top">
                        {shipment.awb ? (
                          <div className="flex items-center gap-1.5">
                            <span className="font-mono text-xs font-bold text-slate-800 bg-slate-100 px-2 py-1 rounded-md border border-slate-200">
                              {shipment.awb}
                            </span>
                            <button
                              type="button"
                              onClick={() => handleCopyAwb(shipment.awb)}
                              className="text-slate-400 hover:text-slate-700 p-1 rounded hover:bg-slate-100 transition-colors"
                              title="Copy AWB number"
                            >
                              <Copy className="w-3.5 h-3.5" />
                            </button>
                          </div>
                        ) : (
                          <span className="text-xs text-slate-400 italic">AWB Pending</span>
                        )}
                      </td>

                      {/* Transit Status Span */}
                      <td className="py-2.5 px-3 align-top">
                        {getStatusBadge(shipment.status)}
                      </td>

                      {/* Dispatch Date */}
                      <td className="py-2.5 px-3 align-top text-xs text-slate-600 font-medium">
                        {shipment.createdAt ? format(new Date(shipment.createdAt), "dd MMM, hh:mm a") : "-"}
                      </td>

                      {/* Actions */}
                      <td className="py-2.5 px-3 align-top">
                        <div className="flex items-center justify-end gap-1.5">
                          {/* Sync Live Tracking */}
                          <button
                            type="button"
                            onClick={() => handleSync(shipmentId)}
                            disabled={syncMutation.isPending}
                            className="p-1.5 text-slate-500 hover:text-blue-600 hover:bg-blue-50 rounded-lg transition-colors border border-transparent hover:border-blue-200"
                            title="Sync live status from courier"
                          >
                            <RefreshCw className={`w-3.5 h-3.5 ${syncMutation.isPending ? "animate-spin text-blue-600" : ""}`} />
                          </button>

                          {/* Print 4x6 Shipping Label */}
                          <button
                            type="button"
                            onClick={() => handlePrintLabel(shipment.labelUrl)}
                            className="p-1.5 text-slate-500 hover:text-emerald-600 hover:bg-emerald-50 rounded-lg transition-colors border border-transparent hover:border-emerald-200"
                            title="Print Courier Shipping Label"
                          >
                            <Printer className="w-3.5 h-3.5" />
                          </button>

                          {/* Live Tracking Modal */}
                          {shipment.awb && (
                            <button
                              type="button"
                              onClick={() => setSelectedTrackingOrder({
                                orderNumber: orderNum,
                                shipment: {
                                  awb: shipment.awb,
                                  courierName: shipment.courierName || shipment.provider,
                                  trackingUrl: shipment.trackingUrl,
                                  status: shipment.status,
                                }
                              })}
                              className="p-1.5 text-slate-500 hover:text-indigo-600 hover:bg-indigo-50 rounded-lg transition-colors border border-transparent hover:border-indigo-200"
                              title="View real-time courier tracking scans"
                            >
                              <Truck className="w-3.5 h-3.5" />
                            </button>
                          )}
                        </div>
                      </td>

                    </tr>
                  );
                })
              )}
            </tbody>
          </table>
        </div>
      </div>

      {/* Pagination Controls */}
      {total > 0 && (
        <div className="p-3 border-t border-slate-200 bg-slate-50/70 flex flex-col sm:flex-row items-center justify-between gap-2.5 text-xs text-slate-600">
          <span>
            Showing <strong className="text-slate-900 font-bold">{(page - 1) * limit + 1}</strong> to{" "}
            <strong className="text-slate-900 font-bold">{Math.min(page * limit, total)}</strong> of{" "}
            <strong className="text-slate-900 font-bold">{total}</strong> shipments
          </span>
          
          <div className="flex items-center gap-2">
            <button
              disabled={page === 1}
              onClick={() => setPage((p) => Math.max(1, p - 1))}
              className="inline-flex items-center gap-1 px-3 py-1.5 border border-slate-300 bg-white hover:bg-slate-50 rounded-lg text-xs font-bold text-slate-700 transition-colors shadow-sm disabled:opacity-40 disabled:cursor-not-allowed"
            >
              <ChevronLeft className="w-3.5 h-3.5" />
              <span>Prev</span>
            </button>
            <span className="text-xs font-bold text-slate-900 px-2 font-mono">
              Page {page} of {totalPages}
            </span>
            <button
              disabled={page >= totalPages}
              onClick={() => setPage((p) => p + 1)}
              className="inline-flex items-center gap-1 px-3 py-1.5 border border-slate-300 bg-white hover:bg-slate-50 rounded-lg text-xs font-bold text-slate-700 transition-colors shadow-sm disabled:opacity-40 disabled:cursor-not-allowed"
            >
              <span>Next</span>
              <ChevronRight className="w-3.5 h-3.5" />
            </button>
          </div>
        </div>
      )}

      {/* Tracking Modal */}
      {selectedTrackingOrder && (
        <AdminTrackingModal
          order={selectedTrackingOrder}
          onClose={() => setSelectedTrackingOrder(null)}
        />
      )}

    </div>
  );
};
