"use client";

import React, { useState, useEffect } from "react";
import Link from "next/link";
import { format } from "date-fns";
import { toast } from "sonner";
import {
  Package,
  Truck,
  MapPin,
  CheckCircle2,
  AlertTriangle,
  Banknote,
  CreditCard,
  Search,
  RefreshCw,
  Copy,
  Printer,
  ChevronRight,
  ChevronLeft,
  Eye,
  Phone,
  MessageCircle,
  Layers
} from "lucide-react";
import { formatPrice } from "@store4riders/shared-utils";
import { useAdminLogisticsStats } from "@/core/hooks/useAdminDashboard";
import { OrderFulfillmentPanel } from "./OrderFulfillmentPanel";
import { OrderQuickViewModal } from "@/modules/admin-orders/components/OrderQuickViewModal";
import { ShippingLabelModal } from "./ShippingLabelModal";
import { AdminTrackingModal } from "./AdminTrackingModal";

type FilterStatus = "ALL" | "NEW" | "PACKED" | "IN_TRANSIT" | "OUT_FOR_DELIVERY" | "DELIVERED" | "ISSUE";

export function AdminLogisticsDashboard() {
  const [activeFilter, setActiveFilter] = useState<FilterStatus>("NEW");
  const [searchInputValue, setSearchInputValue] = useState("");
  const [debouncedSearch, setDebouncedSearch] = useState("");
  const [page, setPage] = useState(1);
  const [limit, setLimit] = useState(15);
  const [fulfillOrderId, setFulfillOrderId] = useState<string | null>(null);
  const [selectedQuickViewOrder, setSelectedQuickViewOrder] = useState<any | null>(null);
  const [selectedLabelOrder, setSelectedLabelOrder] = useState<any | null>(null);
  const [selectedTrackingOrder, setSelectedTrackingOrder] = useState<any | null>(null);

  // Debounce search input to avoid lag and re-render thrashing
  useEffect(() => {
    const handler = setTimeout(() => {
      const term = searchInputValue.trim();
      setDebouncedSearch(term);
      if (term) {
        // Auto-switch to "ALL" so search finds the order across all warehouse stages!
        setActiveFilter("ALL");
      }
      setPage(1);
    }, 350);
    return () => clearTimeout(handler);
  }, [searchInputValue]);

  const handleFilterChange = (newFilter: FilterStatus) => {
    setActiveFilter(newFilter);
    setPage(1);
  };

  const { data, isLoading, isFetching, refetch } = useAdminLogisticsStats({
    page,
    limit,
    status: activeFilter,
    search: debouncedSearch,
  });

  const orders = data?.orders || data?.recentOrders || [];
  const pagination = data?.pagination || {
    totalCount: orders.length,
    page: 1,
    limit: 15,
    totalPages: 1,
  };

  // Copy AWB helper
  const handleCopyAwb = (awb?: string) => {
    if (!awb) return;
    navigator.clipboard.writeText(awb);
    toast.success(`AWB ${awb} copied!`);
  };

  // Copy Order Number helper
  const handleCopyOrderNumber = (orderNumber?: string) => {
    if (!orderNumber) return;
    navigator.clipboard.writeText(orderNumber);
    toast.success(`Order #${orderNumber} copied!`);
  };

  // Open shipping label
  const handleOpenLabel = (labelUrl?: string) => {
    if (labelUrl) {
      window.open(labelUrl, "_blank");
    } else {
      toast.error("Shipping label not yet generated by courier.");
    }
  };

  // WhatsApp customer directly from table
  const handleWhatsApp = (phone: string, fullName: string, orderNumber: string) => {
    if (!phone) return;
    const cleanPhone = phone.replace(/[^0-9]/g, "");
    const formattedPhone = cleanPhone.startsWith("91") ? cleanPhone : `91${cleanPhone}`;
    const msg = `Hello ${fullName}, regarding your Store4Riders order #${orderNumber}: Your package is being processed by our warehouse team.`;
    window.open(`https://wa.me/${formattedPhone}?text=${encodeURIComponent(msg)}`, "_blank");
  };

  const pipeline = (data as any)?.overallPipeline;
  const summary = data?.last24Summary;

  const newOrdersCount = pipeline?.toPack ?? pipeline?.pendingPacking ?? summary?.newOrders ?? 0;
  const packedOrdersCount = pipeline?.packed ?? pipeline?.packedReadyTotal ?? summary?.packedOrders ?? 0;
  const inTransitCount = pipeline?.inTransit ?? pipeline?.inTransitTotal ?? ((summary?.inTransit ?? 0) + (summary?.outForDelivery ?? 0));
  const deliveredCount = pipeline?.delivered ?? pipeline?.deliveredTodayTotal ?? summary?.delivered ?? 0;
  const issuesCount = pipeline?.issues ?? pipeline?.exceptionsTotal ?? summary?.issues ?? 0;

  return (
    <div className="space-y-6">
      
      {/* Top Warehouse Header */}
      <div className="bg-slate-900 text-white rounded-2xl p-6 shadow-sm border border-slate-800 flex flex-col lg:flex-row lg:items-center justify-between gap-4">
        <div>
          <div className="flex items-center gap-3">
            <div className="p-2.5 rounded-xl bg-brand/20 border border-brand/30 text-brand">
              <Truck className="w-6 h-6" />
            </div>
            <div>
              <h1 className="text-xl sm:text-2xl font-black tracking-tight text-white flex items-center gap-2">
                Logistics Dispatch &amp; Tracking
              </h1>
              
            </div>
          </div>
        </div>

        {/* Actions Bar */}
        <div className="flex items-center gap-2">
          <button
            onClick={() => refetch()}
            disabled={isFetching}
            className="inline-flex items-center gap-1.5 px-3 py-2 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-bold border border-slate-700 transition-colors shadow-sm disabled:opacity-50"
            title="Refresh order list"
          >
            <RefreshCw className={`w-3.5 h-3.5 ${isFetching ? "animate-spin text-amber-400" : ""}`} />
            <span>{isFetching ? "Updating..." : "Refresh"}</span>
          </button>
        </div>
      </div>

      {/* 5 Warehouse Pipeline Status Cards */}
      <div className="grid grid-cols-2 md:grid-cols-3 lg:grid-cols-5 gap-3.5">
        
        {/* Card 1: To Pack */}
        <button
          type="button"
          onClick={() => handleFilterChange("NEW")}
          className={`p-3 rounded-xl border-2 text-left flex flex-col justify-between transition-all ${
            activeFilter === "NEW"
              ? "bg-amber-50 border-amber-500 shadow-sm ring-1 ring-amber-500"
              : "bg-white border-slate-200 hover:border-slate-300 shadow-sm"
          }`}
        >
          <div className="flex items-center justify-between">
            <span className="text-xs font-bold text-amber-800 uppercase tracking-wider">
              To Pack
            </span>
            <div className="p-1.5 rounded-lg bg-amber-100 text-amber-700">
              <Package className="w-4 h-4" />
            </div>
          </div>
          <div className="text-xl sm:text-2xl font-black text-slate-900 mt-2 font-mono">
            {isLoading ? "-" : newOrdersCount}
          </div>
        </button>

        {/* Card 2: Packed & Ready */}
        <button
          type="button"
          onClick={() => handleFilterChange("PACKED")}
          className={`p-3 rounded-xl border-2 text-left flex flex-col justify-between transition-all ${
            activeFilter === "PACKED"
              ? "bg-sky-50 border-sky-500 shadow-sm ring-1 ring-sky-500"
              : "bg-white border-slate-200 hover:border-slate-300 shadow-sm"
          }`}
        >
          <div className="flex items-center justify-between">
            <span className="text-xs font-bold text-sky-800 uppercase tracking-wider">
              Packed &amp; Ready
            </span>
            <div className="p-1.5 rounded-lg bg-sky-100 text-sky-700">
              <Package className="w-4 h-4" />
            </div>
          </div>
          <div className="text-xl sm:text-2xl font-black text-slate-900 mt-2 font-mono">
            {isLoading ? "-" : packedOrdersCount}
          </div>
        </button>

        {/* Card 3: In Transit */}
        <button
          type="button"
          onClick={() => handleFilterChange("IN_TRANSIT")}
          className={`p-3 rounded-xl border-2 text-left flex flex-col justify-between transition-all ${
            activeFilter === "IN_TRANSIT"
              ? "bg-blue-50 border-blue-500 shadow-sm ring-1 ring-blue-500"
              : "bg-white border-slate-200 hover:border-slate-300 shadow-sm"
          }`}
        >
          <div className="flex items-center justify-between">
            <span className="text-xs font-bold text-blue-800 uppercase tracking-wider">
              In Transit
            </span>
            <div className="p-1.5 rounded-lg bg-blue-100 text-blue-700">
              <Truck className="w-4 h-4" />
            </div>
          </div>
          <div className="text-xl sm:text-2xl font-black text-slate-900 mt-2 font-mono">
            {isLoading ? "-" : inTransitCount}
          </div>
        </button>

        {/* Card 4: Delivered */}
        <button
          type="button"
          onClick={() => handleFilterChange("DELIVERED")}
          className={`p-3 rounded-xl border-2 text-left flex flex-col justify-between transition-all ${
            activeFilter === "DELIVERED"
              ? "bg-emerald-50 border-emerald-500 shadow-sm ring-1 ring-emerald-500"
              : "bg-white border-slate-200 hover:border-slate-300 shadow-sm"
          }`}
        >
          <div className="flex items-center justify-between">
            <span className="text-xs font-bold text-emerald-800 uppercase tracking-wider">
              Delivered
            </span>
            <div className="p-1.5 rounded-lg bg-emerald-100 text-emerald-700">
              <CheckCircle2 className="w-4 h-4" />
            </div>
          </div>
          <div className="text-xl sm:text-2xl font-black text-slate-900 mt-2 font-mono">
            {isLoading ? "-" : deliveredCount}
          </div>
        </button>

        {/* Card 5: Delivery Issues */}
        <button
          type="button"
          onClick={() => handleFilterChange("ISSUE")}
          className={`p-3 rounded-xl border-2 text-left flex flex-col justify-between transition-all ${
            activeFilter === "ISSUE"
              ? "bg-rose-50 border-rose-500 shadow-sm ring-1 ring-rose-500"
              : "bg-white border-slate-200 hover:border-slate-300 shadow-sm"
          }`}
        >
          <div className="flex items-center justify-between">
            <span className="text-xs font-bold text-rose-800 uppercase tracking-wider">
              Issues
            </span>
            <div className="p-1.5 rounded-lg bg-rose-100 text-rose-700">
              <AlertTriangle className="w-4 h-4" />
            </div>
          </div>
          <div className="text-xl sm:text-2xl font-black text-slate-900 mt-2 font-mono">
            {isLoading ? "-" : issuesCount}
          </div>
        </button>

      </div>

      {/* Orders Table Container (min-h-[580px] keeps layout 100% stable, zero jump) */}
      <div className="bg-white border border-slate-200 shadow-sm rounded-2xl overflow-hidden min-h-[580px] flex flex-col justify-between">
        
        {/* Table Search & Status Chips */}
        <div>
          <div className="p-3 border-b border-slate-200 bg-slate-50/70 flex flex-col xl:flex-row gap-2.5 justify-between items-stretch xl:items-center">
            
            <div className="relative w-full sm:w-64 xl:w-72 shrink-0">
              <Search className="w-3.5 h-3.5 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
              <input
                type="text"
                placeholder="Search order #, customer, city, AWB..."
                value={searchInputValue}
                onChange={(e) => setSearchInputValue(e.target.value)}
                className="w-full pl-8 pr-7 py-1.5 bg-white border border-slate-300 rounded-lg text-xs font-medium focus:outline-none focus:border-brand focus:ring-1 focus:ring-brand shadow-sm"
              />
              {searchInputValue && (
                <button
                  onClick={() => setSearchInputValue("")}
                  className="absolute right-2.5 top-1/2 -translate-y-1/2 text-slate-400 hover:text-slate-700 text-xs font-bold"
                >
                  ✕
                </button>
              )}
            </div>

            {/* Enterprise Status Filter Buttons */}
            <div className="flex items-center gap-1 overflow-x-auto w-full xl:w-auto pb-0.5 xl:pb-0">
              {[
                { label: "All Orders", key: "ALL", icon: Layers },
                { label: "To Pack", key: "NEW", icon: Package },
                { label: "Packed", key: "PACKED", icon: CheckCircle2 },
                { label: "In Transit", key: "IN_TRANSIT", icon: Truck },
                { label: "Delivered", key: "DELIVERED", icon: CheckCircle2 },
                { label: "Issues", key: "ISSUE", icon: AlertTriangle },
              ].map((filter) => {
                const Icon = filter.icon;
                const isActive = activeFilter === filter.key;
                return (
                  <button
                    key={filter.key}
                    type="button"
                    onClick={() => handleFilterChange(filter.key as FilterStatus)}
                    className={`inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-bold whitespace-nowrap transition-all ${
                      isActive
                        ? "bg-slate-900 text-white shadow-sm"
                        : "bg-white text-slate-600 hover:bg-slate-100 hover:text-slate-900 border border-slate-200"
                    }`}
                  >
                    <Icon className={`w-3.5 h-3.5 ${isActive ? "text-amber-400" : "text-slate-400"}`} />
                    <span>{filter.label}</span>
                  </button>
                );
              })}
            </div>

          </div>

          {/* Table Content */}
          {isLoading && orders.length === 0 ? (
            <div className="py-24 text-center">
              <div className="w-8 h-8 border-4 border-brand border-t-transparent rounded-full animate-spin mx-auto mb-3"></div>
              <p className="text-sm font-semibold text-slate-500">Loading warehouse orders...</p>
            </div>
          ) : orders.length === 0 ? (
            <div className="py-24 text-center">
              <Package className="w-12 h-12 text-slate-300 mx-auto mb-3" />
              <h3 className="text-base font-bold text-slate-800">No orders found</h3>
              <p className="text-xs text-slate-500 mt-1 max-w-sm mx-auto">
                {debouncedSearch
                  ? `No orders matching "${debouncedSearch}" in current view.`
                  : "No orders found in this fulfillment stage."}
              </p>
              {activeFilter !== "ALL" && (
                <button
                  type="button"
                  onClick={() => handleFilterChange("ALL")}
                  className="mt-4 inline-flex items-center gap-1.5 px-3.5 py-2 rounded-lg bg-slate-900 text-white text-xs font-bold hover:bg-slate-800 transition-colors shadow-sm"
                >
                  {debouncedSearch ? `Search all orders for "${debouncedSearch}"` : "View all orders"}
                </button>
              )}
              {activeFilter === "ALL" && debouncedSearch && (
                <button
                  type="button"
                  onClick={() => setSearchInputValue("")}
                  className="mt-4 inline-flex items-center gap-1.5 px-3.5 py-2 rounded-lg bg-slate-100 text-slate-700 text-xs font-bold hover:bg-slate-200 border border-slate-300 transition-colors"
                >
                  Clear search
                </button>
              )}
            </div>
          ) : (
            <div className={`overflow-x-auto transition-opacity duration-200 ${isFetching ? "opacity-60" : "opacity-100"}`}>
              <table className="w-full text-left border-collapse table-auto">
                <thead>
                  <tr className="bg-slate-100/70 border-b border-slate-200 text-[11px] font-bold text-slate-500 uppercase tracking-wider">
                    <th className="py-2.5 px-3 w-[17%]">Order &amp; Date</th>
                    <th className="py-2.5 px-3 w-[23%]">Customer &amp; Destination</th>
                    <th className="py-2.5 px-3 w-[15%]">Items</th>
                    <th className="py-2.5 px-3 w-[13%]">Amount &amp; Pay</th>
                    <th className="py-2.5 px-3 w-[18%]">Status &amp; Courier</th>
                    <th className="py-2.5 px-3 w-[14%] text-right">Actions</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100 text-xs text-slate-700">
                  {orders.map((order) => {
                    const isNew = order.fulfillmentStatus === "NEW";
                    const isPacked = order.fulfillmentStatus === "PACKED";
                    const isInTransit = order.fulfillmentStatus === "IN_TRANSIT" || order.fulfillmentStatus === "OUT_FOR_DELIVERY";
                    const isDelivered = order.fulfillmentStatus === "DELIVERED";
                    const isIssue = order.fulfillmentStatus === "ISSUE";

                    const customerPhone = order.customer?.phone || "";
                    const cleanPhone = customerPhone.replace(/[^0-9]/g, "");
                    const streetAddress = [order.customer?.addressLine1, order.customer?.addressLine2].filter(Boolean).join(", ");
                    const cityStatePin = [
                      order.customer?.city,
                      order.customer?.state ? `${order.customer.state}` : "",
                      order.customer?.pincode ? `(${order.customer.pincode})` : ""
                    ].filter(Boolean).join(" ");
                    const fullAddressTooltip = [streetAddress, cityStatePin, order.customer?.country || "India"].filter(Boolean).join(", ");

                    return (
                      <tr key={order.id} className="hover:bg-slate-50/80 transition-colors">
                        
                        {/* Order & Date */}
                        <td className="py-2.5 px-3 font-medium align-top">
                          <div className="flex flex-col">
                            <div className="flex items-center gap-1">
                              <button
                                type="button"
                                onClick={() => setSelectedQuickViewOrder(order)}
                                className="font-bold text-slate-900 hover:text-brand text-left font-mono text-xs"
                                title="Click to view full order details"
                              >
                                #{order.orderNumber}
                              </button>
                              <button
                                type="button"
                                onClick={(e) => {
                                  e.stopPropagation();
                                  handleCopyOrderNumber(order.orderNumber);
                                }}
                                className="text-slate-400 hover:text-slate-700 p-0.5 rounded transition-colors shrink-0"
                                title="Copy order number"
                              >
                                <Copy className="w-3 h-3" />
                              </button>
                            </div>
                            <span className="text-[10px] text-slate-400 mt-0.5">
                              {order.createdAt ? format(new Date(order.createdAt), "dd MMM, hh:mm a") : "-"}
                            </span>
                            {order.slaBreached && (
                              <span className="mt-1 inline-flex items-center gap-0.5 text-[9px] font-bold text-red-600 bg-red-50 border border-red-200 px-1 py-0.5 rounded w-fit">
                                <AlertTriangle className="w-2.5 h-2.5 shrink-0" />
                                Delayed (&gt;24h)
                              </span>
                            )}
                          </div>
                        </td>

                        {/* Customer & Destination */}
                        <td className="py-2.5 px-3 align-top">
                          <div className="flex flex-col gap-0.5 max-w-[210px]" title={fullAddressTooltip}>
                            <div className="flex items-center justify-between gap-1">
                              <span className="font-bold text-slate-900 text-xs truncate">
                                {order.customer?.fullName || "Customer"}
                              </span>
                              <div className="flex items-center gap-1 shrink-0">
                                {customerPhone && (
                                  <button
                                    type="button"
                                    onClick={() => handleWhatsApp(customerPhone, order.customer?.fullName, order.orderNumber)}
                                    title="WhatsApp customer"
                                    className="text-emerald-600 hover:text-emerald-700 p-0.5"
                                  >
                                    <MessageCircle className="w-3 h-3" />
                                  </button>
                                )}
                                {customerPhone && (
                                  <a
                                    href={`tel:${cleanPhone}`}
                                    title="Call customer"
                                    className="text-slate-400 hover:text-slate-700 p-0.5"
                                  >
                                    <Phone className="w-3 h-3" />
                                  </a>
                                )}
                              </div>
                            </div>

                            {streetAddress && (
                              <span className="text-[11px] text-slate-600 truncate leading-snug">
                                {streetAddress}
                              </span>
                            )}

                            <div className="text-[10px] text-slate-500 flex items-center gap-1 truncate font-medium">
                              <MapPin className="w-2.5 h-2.5 text-slate-400 shrink-0" />
                              <span className="truncate">
                                {order.customer?.city || "City"}
                                {order.customer?.state ? `, ${order.customer.state}` : ""}
                                {order.customer?.pincode ? ` (${order.customer.pincode})` : ""}
                              </span>
                            </div>
                          </div>
                        </td>

                        {/* Items & Quantities */}
                        <td className="py-2.5 px-3 align-top">
                          {(() => {
                            const totalUnits = (order.items || []).reduce((sum: number, i: any) => sum + (i.quantity || 1), 0) || order.itemsCount || 1;
                            const distinctCount = order.items?.length || 1;
                            return (
                              <div className="flex flex-col max-w-[150px]">
                                <button
                                  type="button"
                                  onClick={() => setSelectedQuickViewOrder(order)}
                                  className="font-bold text-slate-900 hover:text-brand text-left text-xs flex items-center gap-1"
                                  title="Click to view all items and packing quantities"
                                >
                                  <span className="px-1.5 py-0.5 rounded bg-amber-100/90 text-amber-900 font-mono text-[10px] font-black border border-amber-200 shadow-xs">
                                    {totalUnits} {totalUnits === 1 ? "unit" : "units"}
                                  </span>
                                  {distinctCount > 1 && (
                                    <span className="text-[10px] text-slate-500 font-medium">
                                      ({distinctCount} products)
                                    </span>
                                  )}
                                </button>
                                <span 
                                  className="text-[10px] text-slate-500 truncate cursor-pointer hover:text-slate-800 mt-0.5" 
                                  title={order.items?.map((i: any) => `${i.name} (Qty: ${i.quantity})`).join(", ")}
                                  onClick={() => setSelectedQuickViewOrder(order)}
                                >
                                  {order.items?.[0]?.name ? `${order.items[0].name}${order.items.length > 1 ? ` +${order.items.length - 1} more` : ""}` : "View details"}
                                </span>
                              </div>
                            );
                          })()}
                        </td>

                        {/* Amount & Payment */}
                        <td className="py-2.5 px-3 align-top">
                          <div className="flex flex-col">
                            <span className="font-mono font-bold text-xs text-slate-900">
                              {formatPrice(order.pricing?.total ?? order.totalAmount ?? 0)}
                            </span>
                            <div className="mt-0.5">
                              {order.paymentMethod === "cod" ? (
                                <span className="inline-flex items-center gap-1 px-1.5 py-0.5 rounded text-[9px] font-bold uppercase tracking-wider bg-amber-50 text-amber-800 border border-amber-200 w-fit">
                                  <Banknote className="w-2.5 h-2.5" />
                                  COD
                                </span>
                              ) : (
                                <span className="inline-flex items-center gap-1 px-1.5 py-0.5 rounded text-[9px] font-bold uppercase tracking-wider bg-emerald-50 text-emerald-800 border border-emerald-200 w-fit">
                                  <CreditCard className="w-2.5 h-2.5" />
                                  Prepaid
                                </span>
                              )}
                            </div>
                          </div>
                        </td>

                        {/* Status & Courier Combined */}
                        <td className="py-2.5 px-3 align-top">
                          <div className="flex flex-col gap-1 items-start">
                            {isNew && (
                              <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-bold bg-amber-50 text-amber-800 border border-amber-200 whitespace-nowrap">
                                <span className="w-1.5 h-1.5 rounded-full bg-amber-500"></span>
                                To Pack
                              </span>
                            )}
                            {isPacked && (
                              <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-bold bg-sky-50 text-sky-800 border border-sky-200 whitespace-nowrap">
                                <span className="w-1.5 h-1.5 rounded-full bg-sky-500"></span>
                                Packed &amp; Ready
                              </span>
                            )}
                            {isInTransit && (
                              <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-bold bg-blue-50 text-blue-800 border border-blue-200 whitespace-nowrap">
                                <span className="w-1.5 h-1.5 rounded-full bg-blue-500"></span>
                                {order.fulfillmentStatus === "OUT_FOR_DELIVERY" ? "Out for Delivery" : "In Transit"}
                              </span>
                            )}
                            {isDelivered && (
                              <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-bold bg-emerald-50 text-emerald-800 border border-emerald-200 whitespace-nowrap">
                                <span className="w-1.5 h-1.5 rounded-full bg-emerald-500"></span>
                                Delivered
                              </span>
                            )}
                            {isIssue && (
                              <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-bold bg-rose-50 text-rose-800 border border-rose-200 whitespace-nowrap">
                                <span className="w-1.5 h-1.5 rounded-full bg-rose-500"></span>
                                Issue / NDR
                              </span>
                            )}

                            {order.shipment?.awb ? (
                              <div className="flex flex-col gap-0.5 mt-0.5">
                                <div className="flex items-center gap-1">
                                  <span className="font-bold text-slate-800 uppercase text-[10px] truncate max-w-[80px]">
                                    {order.shipment.courierName || order.shipment.provider || "Carrier"}
                                  </span>
                                  <span className="font-mono text-[10px] font-semibold text-slate-700 bg-slate-100 px-1 py-0.2 rounded border border-slate-200 truncate max-w-[95px]">
                                    {order.shipment.awb}
                                  </span>
                                  <button
                                    onClick={() => handleCopyAwb(order.shipment?.awb)}
                                    className="text-slate-400 hover:text-slate-700 p-0.5 rounded shrink-0"
                                    title="Copy AWB number"
                                  >
                                    <Copy className="w-3 h-3" />
                                  </button>
                                </div>
                                <button
                                  type="button"
                                  onClick={() => setSelectedTrackingOrder(order)}
                                  className="text-[10px] font-bold text-blue-600 hover:text-blue-800 hover:underline flex items-center gap-0.5"
                                  title="View live transit scans"
                                >
                                  <Truck className="w-2.5 h-2.5 text-blue-600" />
                                  <span>Live Tracking</span>
                                </button>
                              </div>
                            ) : (
                              <span className="text-[10px] text-slate-400 font-medium">
                                AWB Pending
                              </span>
                            )}
                          </div>
                        </td>

                        {/* Quick Actions */}
                        <td className="py-2.5 px-3 text-right whitespace-nowrap">
                          <div className="inline-flex items-center justify-end gap-1.5">
                            <button
                              type="button"
                              onClick={() => setSelectedQuickViewOrder(order)}
                              className="inline-flex items-center gap-1 px-2 py-1 rounded-md bg-slate-100 hover:bg-slate-200 text-slate-700 font-bold text-xs border border-slate-200 transition-colors"
                              title="View order details"
                            >
                              <Eye className="w-3 h-3 text-slate-500" />
                              <span>View</span>
                            </button>

                            {isNew ? (
                              <button
                                type="button"
                                onClick={() => setFulfillOrderId(order.id)}
                                className="inline-flex items-center gap-1 px-2.5 py-1 rounded-md bg-amber-500 hover:bg-amber-600 text-white font-bold text-xs shadow-sm transition-colors"
                                title="Pack order and send to courier"
                              >
                                <Package className="w-3 h-3" />
                                <span>Pack</span>
                              </button>
                            ) : (
                              <button
                                type="button"
                                onClick={() => setSelectedLabelOrder(order)}
                                className="inline-flex items-center gap-1 px-2 py-1 rounded-md bg-slate-100 hover:bg-slate-200 text-slate-700 font-bold text-xs border border-slate-200 transition-colors"
                                title="Print 4x6 Shipping Label"
                              >
                                <Printer className="w-3 h-3 text-slate-500" />
                                <span>Label</span>
                              </button>
                            )}
                          </div>
                        </td>

                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          )}
        </div>

        {/* Stable Backend Pagination Bar */}
        <div className="p-4 border-t border-slate-200 bg-slate-50/70 flex flex-col sm:flex-row items-center justify-between gap-3 text-xs text-slate-600">
          <div className="flex items-center gap-3">
            <span>
              Showing{" "}
              <strong className="text-slate-900 font-bold">
                {pagination.totalCount > 0 ? (pagination.page - 1) * pagination.limit + 1 : 0}
              </strong>{" "}
              to{" "}
              <strong className="text-slate-900 font-bold">
                {Math.min(pagination.page * pagination.limit, pagination.totalCount)}
              </strong>{" "}
              of <strong className="text-slate-900 font-bold">{pagination.totalCount}</strong> orders
            </span>

            <div className="flex items-center gap-1.5 border-l border-slate-200 pl-3">
              <span className="text-slate-500">Rows:</span>
              <select
                value={limit}
                onChange={(e) => {
                  setLimit(Number(e.target.value));
                  setPage(1);
                }}
                className="bg-white border border-slate-300 rounded px-2 py-1 text-xs font-semibold focus:outline-none focus:border-brand"
              >
                <option value={15}>15</option>
                <option value={30}>30</option>
                <option value={50}>50</option>
              </select>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={() => setPage((p) => Math.max(1, p - 1))}
              disabled={pagination.page <= 1 || isFetching}
              className="inline-flex items-center gap-1 px-3 py-1.5 rounded-lg border border-slate-300 bg-white hover:bg-slate-50 disabled:opacity-40 disabled:pointer-events-none font-semibold text-slate-700 shadow-sm transition-colors"
            >
              <ChevronLeft className="w-3.5 h-3.5" />
              <span>Previous</span>
            </button>
            <span className="font-bold text-slate-800 px-2">
              Page {pagination.page} of {pagination.totalPages}
            </span>
            <button
              onClick={() => setPage((p) => Math.min(pagination.totalPages, p + 1))}
              disabled={pagination.page >= pagination.totalPages || isFetching}
              className="inline-flex items-center gap-1 px-3 py-1.5 rounded-lg border border-slate-300 bg-white hover:bg-slate-50 disabled:opacity-40 disabled:pointer-events-none font-semibold text-slate-700 shadow-sm transition-colors"
            >
              <span>Next</span>
              <ChevronRight className="w-3.5 h-3.5" />
            </button>
          </div>
        </div>

      </div>

      {/* Quick View Modal */}
      {selectedQuickViewOrder && (
        <OrderQuickViewModal
          order={selectedQuickViewOrder}
          onClose={() => setSelectedQuickViewOrder(null)}
          hideFinancials={false}
        />
      )}

      {/* Fulfillment Drawer Modal */}
      {fulfillOrderId && (
        <OrderFulfillmentPanel
          orderId={fulfillOrderId}
          onClose={() => {
            setFulfillOrderId(null);
            refetch();
          }}
        />
      )}

      {/* 4x6 Direct Thermal Shipping Label Modal */}
      {selectedLabelOrder && (
        <ShippingLabelModal
          order={selectedLabelOrder}
          onClose={() => setSelectedLabelOrder(null)}
        />
      )}

      {/* Live Carrier Tracking Modal */}
      {selectedTrackingOrder && (
        <AdminTrackingModal
          order={selectedTrackingOrder}
          onClose={() => setSelectedTrackingOrder(null)}
        />
      )}

    </div>
  );
}
