/**
 * Sanitizes and normalizes pasted HTML from external websites, Word, and Google Docs.
 * Preserves clean semantic structure (h1-h4, p, ul, ol, li, strong, em, a, table)
 * while stripping fixed widths, inline fonts, fixed colors, and mso comments.
 */
/**
 * Converts Markdown text (commonly generated by ChatGPT, Claude, Gemini, Perplexity)
 * into semantic, responsive HTML with H2/H3 headings, bullet lists, bold text, and tables.
 */
function markdownToHtml(md: string): string {
  let text = md;

  // 1. Process Markdown Tables cleanly
  const tableBlockRegex = /(?:^|\n)((?:\|[^\r\n]+\|\r?\n?)+)/g;
  text = text.replace(tableBlockRegex, (match: string, block: string) => {
    const lines: string[] = block.trim().split(/\r?\n/).filter((l: string) => l.trim().startsWith("|") && l.trim().endsWith("|"));
    const separatorIdx = lines.findIndex((l: string) => /\|[\s-:]+\|/.test(l));
    if (lines.length < 2 || separatorIdx === -1) return match;

    const parseRow = (line: string): string[] => line.split("|").slice(1, -1).map((c: string) => c.trim());
    const headerCols = parseRow(lines[0]);
    const dataLines = lines.filter((_: string, idx: number) => idx !== separatorIdx && idx > 0);
    const dataRows = dataLines.map(parseRow);

    return `\n<table class="w-full my-4 border-collapse border border-slate-300 text-xs sm:text-sm shadow-2xs">
  <thead>
    <tr class="bg-slate-100 font-bold">
      ${headerCols.map((h) => `<th class="border border-slate-300 p-2 text-left font-bold text-slate-800">${h || "-"}</th>`).join("")}
    </tr>
  </thead>
  <tbody>
    ${dataRows.map((row: string[]) => `<tr>${row.map((c: string) => `<td class="border border-slate-300 p-2 text-slate-700">${c || "-"}</td>`).join("")}</tr>`).join("")}
  </tbody>
</table>\n`;
  });

  // 2. Process Headings (H2 for main sections, H3 for sub-points to keep page H1 singular)
  text = text.replace(/^### (.*$)/gim, '<h3 class="font-bold text-base text-slate-900 mt-4 mb-2">$1</h3>');
  text = text.replace(/^## (.*$)/gim, '<h2 class="font-bold text-lg text-slate-900 mt-5 mb-2">$1</h2>');
  text = text.replace(/^# (.*$)/gim, '<h2 class="font-bold text-xl text-slate-900 mt-6 mb-3">$1</h2>');
  text = text.replace(/^#### (.*$)/gim, '<h4 class="font-bold text-sm text-slate-900 mt-3 mb-1">$1</h4>');

  // 3. Process Blockquotes
  text = text.replace(/^\> (.*$)/gim, '<blockquote class="border-l-4 border-[#AB1509] pl-3 py-1 my-3 text-slate-600 bg-slate-50 italic rounded-r">$1</blockquote>');

  // 4. Process Horizontal rules
  text = text.replace(/^(?:---|\*\*\*|___)$/gim, '<hr class="my-4 border-slate-200" />');

  // 5. Process Bold & Italic
  text = text.replace(/\*\*\*(.*?)\*\*\*/g, '<strong><em>$1</em></strong>');
  text = text.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>');
  text = text.replace(/__(.*?)__/g, '<strong>$1</strong>');
  text = text.replace(/\*(.*?)\*/g, '<em>$1</em>');
  text = text.replace(/_(.*?)_/g, '<em>$1</em>');

  // 6. Process Links [text](url)
  text = text.replace(/\[(.*?)\]\((.*?)\)/g, '<a href="$2" target="_blank" rel="noopener noreferrer" class="text-blue-600 underline hover:text-blue-800 font-medium">$1</a>');

  // 7. Process Unordered Lists (- or *)
  text = text.replace(/(?:^|\n)[-*] (.*(?:\r?\n[-*] .*)*)/g, (match: string) => {
    const items = match.trim().split(/\r?\n/).map((line: string) => {
      const itemText = line.replace(/^[-*]\s+/, "");
      return `<li>${itemText}</li>`;
    }).join("");
    return `\n<ul class="list-disc pl-5 my-3 space-y-1">\n${items}\n</ul>\n`;
  });

  // 8. Process Ordered Lists (1. 2.)
  text = text.replace(/(?:^|\n)\d+\. (.*(?:\r?\n\d+\. .*)*)/g, (match: string) => {
    const items = match.trim().split(/\r?\n/).map((line: string) => {
      const itemText = line.replace(/^\d+\.\s+/, "");
      return `<li>${itemText}</li>`;
    }).join("");
    return `\n<ol class="list-decimal pl-5 my-3 space-y-1">\n${items}\n</ol>\n`;
  });

  // 9. Process Paragraphs for remaining text blocks
  const blocks = text.split(/\n{2,}/);
  const formattedBlocks = blocks.map((block: string) => {
    const trimmed = block.trim();
    if (!trimmed) return "";
    if (/^<(h[1-6]|table|ul|ol|blockquote|div|figure|hr)/i.test(trimmed)) {
      return trimmed;
    }
    return `<p>${trimmed.replace(/\n/g, "<br>")}</p>`;
  });

  return formattedBlocks.filter(Boolean).join("\n");
}

/**
 * Enterprise-grade HTML Sanitizer for pasting from:
 * - Microsoft Word (.docx)
 * - Microsoft Excel (.xlsx / .csv)
 * - Google Docs & Google Sheets
 * - AI Tools (ChatGPT, Claude, Gemini, Perplexity)
 * - External Web Pages & PDFs
 *
 * Strips all fixed widths, device-specific fonts, broken XML tags, Word mso-styles,
 * and ensures 100% responsive tables that never overflow mobile screens.
 */
function sanitizePastedHtml(html: string): string {
  let clean = html;

  // 1. Strip scripts, styles, objects, embeds, meta, link, xml
  clean = clean.replace(/<(script|style|object|embed|iframe|applet)[\s\S]*?<\/\1>/gi, "");
  clean = clean.replace(/<(iframe|embed|object)[^>]*>/gi, "");
  clean = clean.replace(/on\w+\s*=\s*["'][^"']*["']/gi, "");
  clean = clean.replace(/<(meta|link)[^>]*>/gi, "");
  clean = clean.replace(/<!--[\s\S]*?-->/g, "");
  clean = clean.replace(/<xml[\s\S]*?<\/xml>/gi, "");

  // 2. Strip HTML/Head/Body wrappers if present (from Word/Excel full page export)
  clean = clean.replace(/<\/?(?:html|head|body)[^>]*>/gi, "");

  // 3. Remove Microsoft Office & XML namespace tags (<o:p>, <w:WordDocument>, etc.)
  clean = clean.replace(/<\/?\w+:[a-z0-9_-]+[^>]*>/gi, "");

  // 4. Transform Word fake bullet lists (MsoListParagraph) into semantic <li> items
  clean = clean.replace(/<p class="MsoListParagraph[^"]*"[^>]*>([\s\S]*?)<\/p>/gi, (_match: string, inner: string) => {
    const item = inner
      .replace(/^[\s\S]*?mso-list:Ignore[\s\S]*?<\/span>(?:\s*<\/span>)*/i, "")
      .replace(/^(\s*<[^>]+>)*\s*[·•\-\*]\s*(<\/[^>]+>\s*)*/, "")
      .replace(/^[\s·•\-\*]+/, "")
      .trim();
    return `<li>${item}</li>`;
  });

  // Group consecutive <li> items into a single <ul class="list-disc pl-5 my-3 space-y-1">
  clean = clean.replace(/(?:<li>[\s\S]*?<\/li>\s*)+/gi, (match: string) => {
    return `\n<ul class="list-disc pl-5 my-3 space-y-1">\n${match.trim()}\n</ul>\n`;
  });

  // 5. Transform Word Headings (MsoHeading1, MsoHeading2, MsoHeading3)
  clean = clean.replace(/<p class="MsoHeading1[^"]*"[^>]*>([\s\S]*?)<\/p>/gi, '<h2 class="font-bold text-xl text-slate-900 mt-6 mb-3">$1</h2>');
  clean = clean.replace(/<p class="MsoHeading2[^"]*"[^>]*>([\s\S]*?)<\/p>/gi, '<h2 class="font-bold text-lg text-slate-900 mt-5 mb-2">$1</h2>');
  clean = clean.replace(/<p class="MsoHeading3[^"]*"[^>]*>([\s\S]*?)<\/p>/gi, '<h3 class="font-bold text-base text-slate-900 mt-4 mb-2">$1</h3>');

  // Map any raw <h1> to <h2> to maintain single H1 SEO standard on category page
  clean = clean.replace(/<h1(?![^>]*class=)[^>]*>([\s\S]*?)<\/h1>/gi, '<h2 class="font-bold text-xl text-slate-900 mt-6 mb-3">$1</h2>');
  clean = clean.replace(/<h2(?![^>]*class=)[^>]*>/gi, '<h2 class="font-bold text-lg text-slate-900 mt-5 mb-2">');
  clean = clean.replace(/<h3(?![^>]*class=)[^>]*>/gi, '<h3 class="font-bold text-base text-slate-900 mt-4 mb-2">');

  // 6. Unwrap <p> tags inside <td> and <th> (eliminates Google Docs / Word line bloat)
  clean = clean.replace(/<(td|th)[^>]*>\s*<p[^>]*>([\s\S]*?)<\/p>\s*<\/\1>/gi, "<$1>$2</$1>");

  // 7. Strip destructive inline styles (fixed widths, fixed colors, fixed fonts, Word margins)
  clean = clean.replace(/style="([^"]*)"/gi, (_match: string, styles: string) => {
    const cleanedStyles = styles
      .replace(/(?:min-width|max-width|width):[^;]+;?/gi, "")
      .replace(/(?:background-color|background):[^;]+;?/gi, "")
      .replace(/(?<![a-z-])color:[^;]+;?/gi, "")
      .replace(/font-family:[^;]+;?/gi, "")
      .replace(/font-size:[^;]+;?/gi, "")
      .replace(/line-height:[^;]+;?/gi, "")
      .replace(/height:[^;]+;?/gi, "")
      .replace(/white-space:\s*nowrap;?/gi, "")
      .replace(/margin(-[a-z]+)?:[^;]+;?/gi, "")
      .replace(/text-indent:[^;]+;?/gi, "")
      .replace(/mso-[a-z0-9-]+:[^;]+;?/gi, "")
      .replace(/panose-1:[^;]+;?/gi, "")
      .trim();
    return cleanedStyles ? `style="${cleanedStyles}"` : "";
  });

  // 8. Strip legacy sizing & border attributes, colgroups, font tags
  clean = clean.replace(/\s+(?:width|height|nowrap|border|cellspacing|cellpadding|bgcolor|align|valign|lang)=["'][^"']*["']/gi, "");
  clean = clean.replace(/<colgroup[\s\S]*?<\/colgroup>/gi, "");
  clean = clean.replace(/<col[^>]*>/gi, "");
  clean = clean.replace(/<\/?font[^>]*>/gi, "");

  // 9. Clean up empty/useless spans, Mso classes, empty style attributes
  clean = clean.replace(/class="Mso[^"]*"/gi, "");
  clean = clean.replace(/class="xl\d+"/gi, "");
  clean = clean.replace(/\s+class=""/gi, "");
  clean = clean.replace(/\s+style=""/gi, "");

  // Unwrap generic <span> with no attributes (multi-pass for nested spans)
  for (let i = 0; i < 3; i++) {
    clean = clean.replace(/<span>([\s\S]*?)<\/span>/gi, "$1");
  }

  // 10. Excel / Word / Web Table enhancement (header generation & responsive wrapper)
  clean = clean.replace(/<table[^>]*>([\s\S]*?)<\/table>/gi, (_match: string, innerTable: string) => {
    let rowsContent = innerTable.replace(/<\/?(?:tbody|thead)[^>]*>/gi, "").trim();
    const hasTh = /<th[\s>]/i.test(rowsContent);

    if (!hasTh) {
      // If table has no <th> (like Excel HTML), convert first <tr> to <thead><tr><th>...</th></tr></thead>
      rowsContent = rowsContent.replace(/<tr[^>]*>([\s\S]*?)<\/tr>/i, (_rowMatch: string, rowCells: string) => {
        const thCells = rowCells.replace(/<td[^>]*>([\s\S]*?)<\/td>/gi, (_tdMatch: string, tdInner: string) => {
          return `<th class="border border-slate-300 bg-slate-100 p-2 text-left font-bold text-slate-800">${tdInner.trim() || "-"}</th>`;
        });
        return `<thead>\n  <tr class="bg-slate-100 font-bold">\n    ${thCells}\n  </tr>\n</thead>\n<tbody>`;
      });
      rowsContent = rowsContent + "\n</tbody>";
    } else {
      rowsContent = rowsContent.replace(/<th(?![^>]*class=)[^>]*>/gi, '<th class="border border-slate-300 bg-slate-100 p-2 text-left font-bold text-slate-800">');
      rowsContent = `<tbody>\n${rowsContent}\n</tbody>`;
    }

    rowsContent = rowsContent.replace(/<td(?![^>]*class=)[^>]*>/gi, '<td class="border border-slate-300 p-2 text-slate-700">');

    return `<div class="overflow-x-auto my-4 rounded-lg border border-slate-200 shadow-2xs"><table class="w-full border-collapse border border-slate-300 text-xs sm:text-sm">\n${rowsContent.trim()}\n</table></div>`;
  });

  return clean.trim();
}

